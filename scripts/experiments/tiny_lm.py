"""A tiny educational language model on LOCALLY GENERATED synthetic text.

WHAT THIS IS NOT. This is not SFT, not fine-tuning, and has nothing to do with
Qwen. No pretrained weights are loaded, no dataset is downloaded, no checkpoint
of any real model is touched. It is a ~200k-parameter model trained from
random initialisation on text this file generates itself, and it exists for
exactly two purposes:

    E2  the causal-leakage experiment - showing what happens when the mask is
        removed, which cannot be demonstrated without a training loop
    E9  decoding-strategy behaviour - which needs a model whose distribution
        means something, not random logits

THE SYNTHETIC LANGUAGE. A tiny formal grammar over lowercase letters, chosen so
that "has the model learned?" has an unambiguous answer:

    sentences look like     the cat sees a dog .
    template                DET NOUN VERB DET NOUN .

The key property is that the LAST token is always "." and the structure is
rigid, so a model that has learned the grammar becomes confident at predictable
positions. Because the grammar is generated by known rules, we can say exactly
what a correct model should predict - unlike natural text, where "is this
output good?" is a judgement call.

DETERMINISM. Every run is seeded. The dataset, the model initialisation and
the batch order are all reproducible from the seed recorded in the output.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass, field

import torch

from alignlab.models.transformer import DecoderOnlyTransformer, TransformerConfig
from alignlab.seeding import set_seed

# --------------------------------------------------------------------------
# the synthetic language
# --------------------------------------------------------------------------

DETERMINERS = ("the", "a")
NOUNS = ("cat", "dog", "bird", "fish")
VERBS = ("sees", "hears", "chases", "likes")

# character-level vocabulary: the letters actually used, plus space and period
CHARS = sorted(set("".join(DETERMINERS + NOUNS + VERBS)) | {" ", "."})
STOI = {c: i for i, c in enumerate(CHARS)}
ITOS = {i: c for c, i in STOI.items()}
VOCAB_SIZE = len(CHARS)


def generate_sentence(rng: random.Random) -> str:
    """One sentence from the grammar: DET NOUN VERB DET NOUN ."""
    return (
        f"{rng.choice(DETERMINERS)} {rng.choice(NOUNS)} {rng.choice(VERBS)} "
        f"{rng.choice(DETERMINERS)} {rng.choice(NOUNS)} ."
    )


def generate_corpus(n_sentences: int, seed: int) -> str:
    """Deterministic corpus. Sentences are separated by a single space."""
    rng = random.Random(seed)
    return " ".join(generate_sentence(rng) for _ in range(n_sentences))


def encode(text: str) -> list[int]:
    return [STOI[c] for c in text]


def decode(ids: list[int]) -> str:
    return "".join(ITOS[int(i)] for i in ids)


# --------------------------------------------------------------------------
# training
# --------------------------------------------------------------------------


@dataclass
class TinyLMResult:
    """Everything needed to reproduce and interpret a run."""

    seed: int
    config: TransformerConfig
    n_params: int
    vocab_size: int
    corpus_chars: int
    block_size: int
    batch_size: int
    steps: int
    learning_rate: float
    causal_mask_enabled: bool
    losses: list[float] = field(default_factory=list)
    final_train_loss: float = float("nan")
    final_val_loss: float = float("nan")

    @property
    def uniform_loss(self) -> float:
        """ln(V): the loss of a model that has learned nothing."""
        return math.log(self.vocab_size)


def get_batch(
    data: torch.Tensor, block_size: int, batch_size: int, generator: torch.Generator
) -> tuple[torch.Tensor, torch.Tensor]:
    """Sample random windows. x is [B, T]; y is x shifted one position left.

    The shift IS the language-modelling objective: predict token t+1 from
    tokens <= t, at every position simultaneously.
    """
    ix = torch.randint(
        len(data) - block_size - 1, (batch_size,), generator=generator
    )
    x = torch.stack([data[i : i + block_size] for i in ix])
    y = torch.stack([data[i + 1 : i + block_size + 1] for i in ix])
    return x, y


@torch.no_grad()
def evaluate(model, data, block_size, batch_size, generator, batches: int = 20) -> float:
    model.eval()
    total = 0.0
    for _ in range(batches):
        x, y = get_batch(data, block_size, batch_size, generator)
        _, loss = model(x, targets=y)
        total += float(loss)
    model.train()
    return total / batches


def train_tiny_lm(
    seed: int = 20260829,
    n_sentences: int = 3000,
    block_size: int = 64,
    max_seq_len: int | None = None,
    batch_size: int = 32,
    steps: int = 600,
    learning_rate: float = 3e-3,
    d_model: int = 96,
    n_layers: int = 3,
    n_heads: int = 4,
    causal: bool = True,
    log_every: int = 100,
    verbose: bool = True,
) -> tuple[DecoderOnlyTransformer, TinyLMResult]:
    """Train the tiny LM. Returns (model, result).

    Args:
        block_size: training window length. The loss is computed over windows
            of this many characters.
        max_seq_len: the model's positional capacity. Defaults to
            block_size + 128 so that generation can run PAST the training
            window without hitting the length guard. Note that positions
            beyond block_size were never seen during training, so continuing
            far past it is extrapolation - acceptable here because every
            decoding strategy is compared under identical conditions.
        causal: when False the causal mask is DISABLED, which is experiment E2.
            The model may then read the token it is being asked to predict.
    """
    set_seed(seed)
    generator = torch.Generator().manual_seed(seed)

    corpus = generate_corpus(n_sentences, seed)
    data = torch.tensor(encode(corpus), dtype=torch.long)
    split = int(0.9 * len(data))
    train_data, val_data = data[:split], data[split:]

    if max_seq_len is None:
        max_seq_len = block_size + 128

    cfg = TransformerConfig(
        vocab_size=VOCAB_SIZE,
        d_model=d_model,
        n_layers=n_layers,
        n_heads=n_heads,
        max_seq_len=max_seq_len,
    )
    model = DecoderOnlyTransformer(cfg)

    if not causal:
        _disable_causal_masking(model)

    optimizer = torch.optim.AdamW(model.parameters(), lr=learning_rate)
    result = TinyLMResult(
        seed=seed,
        config=cfg,
        n_params=model.num_parameters(),
        vocab_size=VOCAB_SIZE,
        corpus_chars=len(corpus),
        block_size=block_size,
        batch_size=batch_size,
        steps=steps,
        learning_rate=learning_rate,
        causal_mask_enabled=causal,
    )

    if verbose:
        print(f"  vocab={VOCAB_SIZE} chars, corpus={len(corpus):,} chars, "
              f"params={result.n_params:,}")
        print(f"  causal mask: {'ENABLED' if causal else 'DISABLED (E2)'}")
        print(f"  uniform-guess loss ln({VOCAB_SIZE}) = {result.uniform_loss:.4f}")

    model.train()
    for step in range(1, steps + 1):
        x, y = get_batch(train_data, block_size, batch_size, generator)
        _, loss = model(x, targets=y)

        optimizer.zero_grad(set_to_none=True)
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()

        result.losses.append(float(loss))
        if verbose and (step % log_every == 0 or step == 1):
            print(f"  step {step:>4} | train loss {float(loss):.4f}")

    result.final_train_loss = evaluate(model, train_data, block_size, batch_size, generator)
    result.final_val_loss = evaluate(model, val_data, block_size, batch_size, generator)
    return model, result


def _disable_causal_masking(model: DecoderOnlyTransformer) -> None:
    """Monkey-patch every attention layer to attend BIDIRECTIONALLY.

    This is experiment E2's intervention and nothing else should ever call it.
    Implemented by patching rather than by adding a config flag, so that the
    production model has no switch capable of silently disabling causality.
    """
    from alignlab.models import attention as attention_module
    from alignlab.models import transformer as transformer_module

    def no_mask(seq_len, device=None, key_len=None):
        key_len = seq_len if key_len is None else key_len
        return torch.ones(seq_len, key_len, dtype=torch.bool, device=device)

    transformer_module.causal_mask = no_mask
    model._causal_disabled = True


def restore_causal_masking() -> None:
    """Undo _disable_causal_masking. Always call this after E2."""
    from alignlab.models import attention as attention_module
    from alignlab.models import transformer as transformer_module

    transformer_module.causal_mask = attention_module.causal_mask


if __name__ == "__main__":
    print("Training the tiny educational LM (synthetic grammar, no downloads)")
    model, result = train_tiny_lm()
    print(f"\nfinal train loss {result.final_train_loss:.4f} | "
          f"val loss {result.final_val_loss:.4f} | "
          f"uniform {result.uniform_loss:.4f}")
